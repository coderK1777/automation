"""Persisted, bounded UTC observations from existing verified public HTTPS.

HTTP Date is a one-second-resolution estimate. A CDN/managed TLS intermediary
may generate it; this cannot independently certify the exchange signing clock
or replace operating-system NTP. It still detects absent/stale evidence,
material offset and wall-clock jumps without assuming clock health is true.
"""
from datetime import datetime, timedelta
from email.utils import parsedate_to_datetime
import math
import time

from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError

from tradebot.data_models import TelemetryState
from tradebot.db import aware, get_db, utcnow
from tradebot.security import identity
from tradebot_delta.clock import monotonic_domain

router = APIRouter(prefix="/api/v1", tags=["clock evidence"])
SOURCES = {"production": "https://api.india.delta.exchange", "demo": "https://cdn-ind.testnet.deltaex.org"}
MAX_AGE_SECONDS = 120
MAX_RTT_SECONDS = 2
MAX_OFFSET_SECONDS = 5
MAX_WALL_JUMP_SECONDS = .25
CAVEAT = "HTTPS Date can be generated by an intermediary; this bounded estimate does not certify exchange signing time or replace NTP."
_BLOCKING_ISSUES = {"CLOCK_OFFSET_EXCEEDED", "WALL_CLOCK_JUMP", "FUTURE_LOCAL_SAMPLE", "FUTURE_MONOTONIC_SAMPLE"}


def _finite(value):
    result = float(value)
    if not math.isfinite(result):
        raise ValueError("Non-finite clock observation")
    return result


def evaluate_observation(observation: dict) -> dict:
    environment = observation.get("environment", "production")
    payload = {"measurement": "HTTPS_DATE", "environment": environment,
               "source": SOURCES.get(environment), "usable": False, "issues": [], "caveat": CAVEAT,
               "verification_scope": observation.get("verification_scope", "PUBLIC_HTTPS_RESPONSE")}
    issues = payload["issues"]
    try:
        domain = observation["monotonic_domain"]
        stamp = _finite(observation["monotonic_sample"])
        if not domain or domain != monotonic_domain() or stamp < 0:
            raise ValueError("Clock monotonic provenance is unavailable")
        if stamp > time.monotonic()+MAX_WALL_JUMP_SECONDS:
            issues.append("FUTURE_MONOTONIC_SAMPLE")
        payload.update(monotonic_sample=stamp, monotonic_domain=domain)
    except (ValueError, TypeError, KeyError):
        issues.append("MONOTONIC_PROVENANCE_UNAVAILABLE")
    if environment not in SOURCES or observation.get("source") != SOURCES.get(environment) or observation.get("public_source_verified") is not True:
        issues.append("UNVERIFIED_CLOCK_SOURCE")
    try:
        sent = aware(datetime.fromisoformat(observation["request_started_at"]))
        received = aware(datetime.fromisoformat(observation["response_received_at"]))
        rtt, wall = _finite(observation["round_trip_seconds"]), _finite(observation["wall_elapsed_seconds"])
        if rtt < 0 or rtt > MAX_RTT_SECONDS:
            issues.append("CLOCK_RTT_UNCERTAIN")
        if abs(wall-rtt) > MAX_WALL_JUMP_SECONDS or abs((received-sent).total_seconds()-wall) > MAX_WALL_JUMP_SECONDS or wall < 0:
            issues.append("WALL_CLOCK_JUMP")
        if received > utcnow()+timedelta(seconds=MAX_WALL_JUMP_SECONDS):
            issues.append("FUTURE_LOCAL_SAMPLE")
        payload.update(sampled_at=received.isoformat(), request_started_at=sent.isoformat(),
                       round_trip_seconds=rtt, wall_elapsed_seconds=wall)
    except (ValueError, TypeError, KeyError):
        issues.append("INVALID_LOCAL_CLOCK_OBSERVATION")
        return payload
    age = observation.get("age_header")
    try:
        cache_age = 0 if age is None else int(age)
        if cache_age < 0:
            raise ValueError("Negative cache age")
        if cache_age > 0:
            issues.append("CACHED_DATE_UNUSABLE")
        payload["cache_age_seconds"] = cache_age
        payload["cache_age_header_present"] = age is not None
    except (ValueError, TypeError):
        issues.append("INVALID_CACHE_AGE")
    date_header = observation.get("date_header")
    if not isinstance(date_header, str) or not date_header or len(date_header) > 128:
        issues.append("DATE_HEADER_UNAVAILABLE")
        return payload
    try:
        server = parsedate_to_datetime(date_header)
        if server.tzinfo is None or server.utcoffset().total_seconds() != 0:
            raise ValueError("HTTP Date requires an explicit UTC timezone")
    except (ValueError, TypeError, AttributeError, OverflowError):
        issues.append("INVALID_DATE_HEADER")
        return payload
    # Date represents a one-second bin, not an exact clock instant. Center
    # that bin and include its half-width plus half the measured network RTT.
    offset = (server+timedelta(seconds=.5) - (sent+(received-sent)/2)).total_seconds()
    uncertainty = .5+max(0, rtt)/2
    bound = abs(offset)+uncertainty
    payload.update(server_time=server.isoformat(), offset_seconds=offset,
                   uncertainty_seconds=uncertainty, absolute_offset_bound_seconds=bound)
    # A known cached Date is unusable rather than evidence of host skew.
    # An uncached verified observation outside the bound blocks immediately.
    if bound > MAX_OFFSET_SECONDS and "CACHED_DATE_UNUSABLE" not in issues and "INVALID_CACHE_AGE" not in issues and "UNVERIFIED_CLOCK_SOURCE" not in issues:
        issues.append("CLOCK_OFFSET_EXCEEDED")
    payload["usable"] = not issues
    return payload


def record_clock_observation(db: Session, observation: dict):
    sample = evaluate_observation(observation)
    environment = sample.get("environment")
    if environment not in SOURCES:
        return
    domain = monotonic_domain()
    if domain is None:
        return  # An unidentifiable monotonic domain cannot establish health.
    key = "clock:"+environment+":"+domain
    query = select(TelemetryState).where(TelemetryState.key == key).with_for_update().execution_options(populate_existing=True)
    row = db.scalar(query)
    if row is None:
        try:
            with db.begin_nested():
                row = TelemetryState(key=key, payload={})
                db.add(row)
                db.flush()
        except IntegrityError:
            row = db.scalar(query)
            if row is None:
                raise
    previous = row.payload if row else {}
    ordered = sample.get("monotonic_domain") == domain and "monotonic_sample" in sample
    order = sample["monotonic_sample"] if ordered else time.monotonic()
    if ordered and order <= previous.get("last_observed_monotonic", -1):
        # Delayed callbacks cannot clear a more recent unsafe measurement.
        return
    evidence = dict(previous)
    evidence["last_observed_monotonic"] = order
    evidence["monotonic_domain"] = domain
    evidence["last_attempt"] = sample
    blocking = bool(set(sample["issues"]) & _BLOCKING_ISSUES)
    if sample["usable"]:
        evidence["last_usable"] = sample
        evidence["blocking_observation"] = None
    elif blocking:
        evidence["blocking_observation"] = sample
    # Missing/cached/slow responses retain a still-fresh last usable sample;
    # a measured offset/jump remains blocking until a new usable observation.
    row.payload = evidence
    row.updated_at = utcnow()


def clock_status(db: Session, environment="production") -> dict:
    result = {"healthy": False, "environment": environment, "issues": [], "age_seconds": None,
              "max_age_seconds": MAX_AGE_SECONDS, "max_round_trip_seconds": MAX_RTT_SECONDS,
              "max_offset_bound_seconds": MAX_OFFSET_SECONDS, "caveat": CAVEAT}
    domain = monotonic_domain()
    row = db.scalar(select(TelemetryState).where(TelemetryState.key == "clock:"+environment+":"+domain)
                    .execution_options(populate_existing=True)) if domain else None
    if row is None:
        result["issues"] = ["CLOCK_EVIDENCE_MISSING"]
        return result
    evidence = row.payload
    sample = evidence.get("last_usable")
    blocker = evidence.get("blocking_observation")
    result["last_attempt"] = evidence.get("last_attempt")
    result["sample"] = sample
    if blocker:
        result["issues"].extend(blocker.get("issues", ["UNSAFE_CLOCK_OBSERVATION"]))
    if not sample:
        result["issues"].append("CLOCK_EVIDENCE_MISSING")
        return result
    try:
        sampled_at = datetime.fromisoformat(sample["sampled_at"])
        age = (utcnow()-aware(sampled_at)).total_seconds()
        monotonic_age = time.monotonic()-_finite(sample["monotonic_sample"])
        result["age_seconds"] = round(max(age, monotonic_age), 6)
        if age < -MAX_WALL_JUMP_SECONDS:
            result["issues"].append("CLOCK_EVIDENCE_IN_FUTURE")
        elif max(age, monotonic_age) > MAX_AGE_SECONDS:
            result["issues"].append("CLOCK_EVIDENCE_STALE")
        if monotonic_age < -MAX_WALL_JUMP_SECONDS or sample.get("monotonic_domain") != domain:
            result["issues"].append("INVALID_MONOTONIC_EVIDENCE")
        if abs(age-monotonic_age) > MAX_WALL_JUMP_SECONDS:
            result["issues"].append("WALL_CLOCK_JUMP_SINCE_SAMPLE")
        if sample.get("usable") is not True or sample.get("source") != SOURCES.get(environment):
            result["issues"].append("INVALID_CLOCK_EVIDENCE")
        if _finite(sample["absolute_offset_bound_seconds"]) > MAX_OFFSET_SECONDS or _finite(sample["round_trip_seconds"]) > MAX_RTT_SECONDS:
            result["issues"].append("CLOCK_MEASUREMENT_UNCERTAIN")
    except (ValueError, TypeError, KeyError):
        result["issues"].append("INVALID_CLOCK_EVIDENCE")
    result["healthy"] = not result["issues"]
    return result


def clock_healthy(db: Session, environment="production") -> bool:
    return clock_status(db, environment)["healthy"]


@router.get("/clock")
def clock_evidence(db: Session = Depends(get_db), principal=Depends(identity)):
    return clock_status(db)
